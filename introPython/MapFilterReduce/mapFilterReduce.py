# map() , filter() and reduce() are global higher order functions
# used for functional programming to process iterables without explicit loops. 


# MAP

# map() applies a given function to every element in an iterable, 
# returning a new iterable with the transformed values.  
# For example, it can convert all numbers in a list to their squares.

# FILTER

# filter() applies a condition (a function returning boolean values) to an iterable, 
# returning a new iterable containing only the elements for which the function returns True.  
# It effectively removes unwanted items based on the specified criteria.

# REDUCE

# reduce() (imported from functools) applies a function of two arguments cumulatively 
# to the items of an iterable from left to right, reducing the sequence to 
# a single final value.  Common uses include summing all numbers in a list or 
# calculating a product. 


# These functions can be chained together to perform complex data transformations efficiently,
# such as filtering a list, mapping a function to the remaining items, 
# and then reducing the result to a single aggregate value.

